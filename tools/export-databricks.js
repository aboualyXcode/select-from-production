#!/usr/bin/env node
/* Generates the /databricks folder from the same sources the playground uses:
   - 00_create_dataset.sql  creates the Stagedoor tables in a schema and loads every row
   - challenges/<track>/<nn>-<id>.sql   one file per challenge: the brief, setup and an empty workspace
   - solutions/<track>/<nn>-<id>.sql    reference and alternative solutions
   Usage: node tools/export-databricks.js */
'use strict';
const fs = require('fs'), path = require('path');
global.window = undefined;
['sql/parser', 'sql/functions', 'sql/engine', 'data', 'grader', 'challenges-1', 'challenges-2'].forEach(f => require(path.join(__dirname, '..', 'js', f + '.js')));
const X = global.SQLX;
const OUT = path.join(__dirname, '..', 'databricks');

const typeSql = (t, name) => {
  if (t === 'ARRAY') return name === 'items' ? 'ARRAY<STRUCT<event_id: INT, ticket_type: STRING, qty: INT, unit_price: DOUBLE>>' : 'ARRAY<STRING>';
  return t;
};
const lit = (v, t, name) => {
  if (v == null) return 'NULL';
  if (t === 'INT' || t === 'DOUBLE') return String(v);
  if (t === 'BOOLEAN') return v ? 'true' : 'false';
  if (t === 'DATE') return `DATE'${v}'`;
  if (t === 'TIMESTAMP') return `TIMESTAMP'${v}'`;
  if (t === 'ARRAY' && name === 'items') return v.length ? `array(${v.map(i => `named_struct('event_id', ${i.event_id}, 'ticket_type', '${i.ticket_type}', 'qty', ${i.qty}, 'unit_price', CAST(${i.unit_price} AS DOUBLE))`).join(', ')})` : `CAST(array() AS ARRAY<STRUCT<event_id: INT, ticket_type: STRING, qty: INT, unit_price: DOUBLE>>)`;
  if (t === 'ARRAY') return v.length ? `array(${v.map(x => `'${x}'`).join(', ')})` : 'CAST(array() AS ARRAY<STRING>)';
  return `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
};

function datasetSql() {
  const lines = [
    '-- Stagedoor dataset for SELECT * FROM production.',
    '-- Run this once in a Databricks SQL editor or notebook. It creates the 15 practice tables',
    '-- in the schema of your choice (default: main.stagedoor) and loads every row.',
    '-- Generated by tools/export-databricks.js; do not edit by hand.',
    '',
    'CREATE SCHEMA IF NOT EXISTS stagedoor;',
    'USE SCHEMA stagedoor;',
    '',
  ];
  for (const t of X.dataset.build()) {
    lines.push(`-- ${t.name}: ${t.description}`);
    lines.push(`CREATE OR REPLACE TABLE ${t.name} (\n  ${t.cols.map(c => `${c.name} ${typeSql(c.type, c.name)}`).join(',\n  ')}\n) COMMENT '${t.description.replace(/'/g, "\\'")}';`);
    for (let i = 0; i < t.rows.length; i += 200) {
      const chunk = t.rows.slice(i, i + 200);
      lines.push(`INSERT INTO ${t.name} VALUES\n  ${chunk.map(r => '(' + r.map((v, j) => lit(v, t.cols[j].type, t.cols[j].name)).join(', ') + ')').join(',\n  ')};`);
    }
    lines.push('');
  }
  lines.push(`SELECT 'Loaded ${X.dataset.build().length} tables' AS status;`);
  return lines.join('\n') + '\n';
}

const plain = html => html.replace(/<code>|<\/code>/g, '`').replace(/<b>|<\/b>/g, '').replace(/<i>|<\/i>/g, '').replace(/&gt;/g, '>').replace(/&lt;/g, '<').replace(/<[^>]+>/g, '');
const wrap = (text, width) => { const out = []; let line = ''; text.split(/\s+/).forEach(w => { if ((line + ' ' + w).trim().length > width) { out.push(line); line = w; } else line = (line + ' ' + w).trim(); }); if (line) out.push(line); return out; };
const comment = (text, width) => wrap(plain(text), width || 96).map(l => '-- ' + l).join('\n');

function main() {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(path.join(OUT, 'challenges'), { recursive: true });
  fs.mkdirSync(path.join(OUT, 'solutions'), { recursive: true });
  fs.writeFileSync(path.join(OUT, '00_create_dataset.sql'), datasetSql());
  X.TRACKS.forEach((t, ti) => {
    const list = X.CHALLENGES.filter(c => c.track === t.id);
    const dir = `${String(ti + 1).padStart(2, '0')}-${t.id}`;
    fs.mkdirSync(path.join(OUT, 'challenges', dir), { recursive: true });
    fs.mkdirSync(path.join(OUT, 'solutions', dir), { recursive: true });
    list.forEach((c, i) => {
      const file = `${String(i + 1).padStart(2, '0')}-${c.id}.sql`;
      const head = [
        `-- ${t.title} · ${['', 'Warm-up', 'Core', 'Hard'][c.level]} · ${c.title}`,
        `-- Playground: https://aboualyxcode.github.io/select-from-production/#${c.id}`,
        '--',
        comment(c.scenario),
        '--',
        comment('TASK: ' + c.task),
        '--',
        `-- Tables: ${c.tables.join(', ')}${c.mode === 'state' ? '\n-- This challenge changes data. The setup below creates the tables it needs; rerun it to start over.' : ''}`,
        c.mode === 'state' ? `-- Check your result with:\n--   ${c.check}` : null,
        c.idempotent ? '-- Your statements must be idempotent: running them twice must leave the same result.' : null,
        '',
        'USE SCHEMA stagedoor;',
        '',
      ].filter(x => x != null);
      const setup = c.setup ? ['-- Setup', c.setup.replace(/CREATE TABLE /g, 'CREATE OR REPLACE TABLE ').trim().replace(/;?\s*$/, ';'), ''] : [];
      const body = c.starter ? ['-- The query you were handed:', c.starter.trim() + ';', ''] : ['-- Your SQL here', ''];
      fs.writeFileSync(path.join(OUT, 'challenges', dir, file), head.concat(setup, body).join('\n') + '\n');
      const altBlock = c.mode === 'state'
        ? ['-- Another way (commented out: run it instead of the reference solution, after rerunning the setup)', c.alt.trim().replace(/;?\s*$/, ';').split('\n').map(l => '-- ' + l).join('\n')]
        : ['-- Another way', c.alt.trim().replace(/;?\s*$/, ';')];
      const sol = head.concat(setup, ['-- Reference solution', c.solution.trim() + ';', ''], altBlock, ['', comment('WHY IT MATTERS: ' + c.explain)], c.mode === 'state' ? ['', c.check + ';'] : []);
      fs.writeFileSync(path.join(OUT, 'solutions', dir, file), sol.join('\n') + '\n');
    });
  });
  const index = ['# Running the challenges on Databricks', '',
    'Everything in the playground also runs on a Databricks SQL warehouse or a notebook.', '',
    '1. Open `00_create_dataset.sql` in the Databricks SQL editor, choose a catalog you can create schemas in, and run it. It creates the schema `stagedoor` with the 15 practice tables.',
    '2. Open any file in `challenges/`, write your SQL under `-- Your SQL here`, and run it.',
    '3. Compare with the matching file in `solutions/`, which has the reference solution, an alternative, and the lesson.', '',
    'Challenges that change data (the Pipelines track) start with a setup block that creates their own tables, so rerunning the file starts the exercise over.', '',
    'These files are generated from the playground by `node tools/export-databricks.js`.', '',
    '| # | Track | Challenges |', '|---|---|---|',
    ...X.TRACKS.map((t, i) => `| ${i + 1} | ${t.title} | ${X.CHALLENGES.filter(c => c.track === t.id).length} |`)].join('\n');
  fs.writeFileSync(path.join(OUT, 'README.md'), index + '\n');
  console.log(`Wrote ${X.CHALLENGES.length} challenges and solutions, and the dataset script, to databricks/`);
}
main();
